const norm = value => String(value || '').toLowerCase().replace(/[^a-z0-9]/g, '');

// Rename catalog skills to their current English names, in place, keeping ids and
// the original catalog name. Applies to every object that shares the skill.
export function applyCurrentSkillNames(skills) {
  const current = new Map(Object.entries(PERSONA_SKILL_NAME_ALIASES).map(([now, old]) => [norm(old), now]));
  for (const skill of skills) {
    const name = current.get(norm(skill.name));
    if (name) { skill.catalogName = skill.name; skill.name = name; }
  }
  return skills;
}

// Replace catalog recommendations for listed Personas, resolving names to transferable skills.
export function withPersonaRecommendations(personas, transferableSkills) {
  const byName = new Map(transferableSkills.map(skill => [norm(skill.name), skill]));
  const listed = new Map(Object.entries(PERSONA_RECOMMENDATIONS).map(([name, entry]) => [norm(name), entry]));
  return personas.map(persona => {
    const entry = listed.get(norm(persona.name));
    if (!entry || !entry.skills.length) return persona;
    const recommendedSkills = entry.skills.map(skill => {
      const resolved = byName.get(norm(skill.name)) || byName.get(norm(PERSONA_SKILL_NAME_ALIASES[skill.name]));
      return { name: resolved?.name || skill.name, listedName: skill.name, sourceName: resolved?.sourceName, skillId: resolved?.id, priority: skill.priority, ...(skill.paymentEvent ? { paymentEvent: true } : {}) };
    });
    return { ...persona, recommendedSkills, recommendationsOnly: true, recommendationSource: 'lufel-s-a-tier-lv8-2026-09-26' };
  });
}
